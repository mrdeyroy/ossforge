from ossforge import policy


def test_actual_ytdlp_explicit_contribution_ban():
    text = '''# NO AI / NO LLM POLICY
This project strictly forbids the usage of LLMs, agents, or any other AI tools for any kind of contribution.
- No AI / no LLMs for issues or bug reports.
- No AI / no LLMs for patches or pull requests (including PR descriptions).
'''
    result = policy.scan_text(text, 'CONTRIBUTING.md')
    assert result.anti_ai and result.source == 'CONTRIBUTING.md'


def test_wrapped_usage_ban_without_heading():
    assert policy.scan_text('This project strictly forbids the usage of\nLLMs, agents, or any other AI tools for any kind of contribution.').anti_ai


def test_no_ban_or_quoted_title_is_not_a_prohibition():
    for text in ('We do not forbid the usage of LLMs for contributions.', 'There is no AI ban here.',
                 'We discuss a "NO AI / NO LLM POLICY" adopted by other projects.',
                 '# AI policy\nAI assistance is allowed with disclosure.'):
        assert not policy.scan_text(text).anti_ai


def test_disclosure_and_limited_tool_policy_not_blanket_bans():
    for text in ('The project requires disclosure of AI use for contributions.',
                 'This project forbids the use of AI tools for legal attestations, not contributions.',
                 'This project does not strictly forbid the usage of LLMs for contributions.'):
        assert not policy.scan_text(text).anti_ai


def test_unclassified_restrictions_are_review_holds_not_false_clean():
    for text in ('We forbid the use of AI for contributions.',
                 'This repo prohibits the use of LLMs for any contribution.',
                 'We ban AI tools for any contribution.',
                 'AI-generated contributions are not accepted.',
                 'No AI or LLM-generated code in pull requests.',
                 'Contributions generated by AI tools are strictly forbidden.',
                 'This repo forbids usage of ChatGPT for pull requests.',
                 'The usage of LLMs for contributions is forbidden.'):
        result = policy.scan_text(text)
        assert result.anti_ai or result.agent_review, text


def test_hypothetical_quoted_and_legal_scope_need_review_not_universal_ban():
    for text in ('If this project strictly forbids the usage of LLMs for contributions, ask first.',
                 '> This project strictly forbids the usage of LLMs for contributions.',
                 'This project forbids the use of AI tools for legal attestations, not contributions.'):
        result = policy.scan_text(text)
        assert not result.anti_ai and result.agent_review


def test_review_result_is_enforced_by_issue_consumer():
    from ossforge import vet
    result = policy.scan_text('We ban AI tools for any contribution.', 'CONTRIBUTING.md')
    decision, reasons = vet.decide(assigned=False, claimed=False, open_pr_count=0,
        clear=True, has_contributing=True, anti_ai=result, repo_ok=True)
    assert decision == 'skip' and any('policy needs review' in r for r in reasons)


def test_permission_or_human_negation_does_not_suppress_separate_universal_ban():
    ban = 'This project strictly forbids the usage of LLMs, agents, or any other AI tools for any kind of contribution.'
    for prefix in ('We do not forbid human help. ', 'AI is welcome for brainstorming. ',
                   'Autonomous agents are not prohibited from opening PRs; however, '):
        assert policy.scan_text(prefix + ban).anti_ai
    assert not policy.scan_text('We do not forbid human help. AI contributions are welcome.').agent_review
